const root = require.resolve("@tabler/icons-react-native").replace(/dist\/.*$/, "dist/esm/icons/");
const number = (value) => Number(value);
function pathData(tag, a) {
  switch (tag) {
    case "path":
      return a.d;
    case "circle":
    case "ellipse": {
      const [cx, cy] = [number(a.cx), number(a.cy)];
      const [rx, ry] = tag === "circle" ? [number(a.r), number(a.r)] : [number(a.rx), number(a.ry)];
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`;
    }
    case "rect": {
      const [x, y, w, h] = [a.x ?? 0, a.y ?? 0, a.width, a.height].map(number);
      const r = Math.min(number(a.rx ?? a.ry ?? 0), w / 2, h / 2);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
    }
    case "line":
      return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline":
    case "polygon":
      return `M${a.points.trim().split(/\s+/).join("L")}${tag === "polygon" ? "Z" : ""}`;
    default:
      throw new Error(`Unsupported Tabler element: ${tag}`);
  }
}
const cases = [];
for (const [name, component] of Object.entries(icons)) {
  const source = await NodeFSP.readFile(`${root}${component}.mjs`, "utf8");
  const [, type, nodes] = source.match(
    /createReactNativeComponent\("(\w+)", "[^"]+", "\w+", (\[.*\])\);/,
  );
  const d = JSON.parse(nodes)
    .map(([tag, attributes]) => pathData(tag, attributes))
    .join("");
  cases.push(`    case '${name}': return ['${type}', '${d}', '2'];`);
}
// The Android navigation bar draws its own Material vectors (T3WorkspaceNavigationModule.kt).
for (const tab of ["chats", "inbox", "settings"]) {
  const xml = await NodeFSP.readFile(
    new URL(
      `../../../apps/mobile/modules/t3-native-controls/android/src/main/res/drawable/t3_${tab}.xml`,
      import.meta.url,
    ),
    "utf8",
  );
  const d = [...xml.matchAll(/android:pathData="([^"]+)"/g)].map((match) => match[1]).join("");
  const stroke = /android:strokeWidth="([\d.]+)"/.exec(xml)?.[1];
  cases.push(
    `    case 'tab.${tab}': return ['${stroke ? "outline" : "filled"}', '${d}', '${stroke ?? "0"}'];`,
  );
}
const directory = new URL("../entry/src/main/ets/generated/", import.meta.url);
await NodeFSP.mkdir(directory, { recursive: true });
await NodeFSP.writeFile(
  new URL("symbols.ets", directory),
  `// Generated by scripts/generate-symbols.mjs.\nexport function symbolPath(name: string): string[] {\n  switch (name) {\n${cases.join("\n")}\n    default: return ['outline', '', '2'];\n  }\n}\n`,
);
